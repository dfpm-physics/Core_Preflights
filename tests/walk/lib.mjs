/* ── The guard ─────────────────────────────────────────────────────────────────
 * The walk runs only against a page served from this machine, and refuses any request to the production project.
 * "Local" is exactly localhost, 127.0.0.1 or [::1], over http, with nothing after the host but a port. */
export function assertLocalBase(base) {
  let u;
  try { u = new URL(base); } catch { throw new Error('REFUSED: the base address is not a web address.'); }
  const ok = u.protocol === 'http:' && ['localhost', '127.0.0.1', '[::1]'].includes(u.hostname)
    && !u.username && !u.password && (u.pathname === '/' || u.pathname === '') && !u.search && !u.hash;
  if (!ok) throw new Error('REFUSED: the walk runs only against http://localhost, http://127.0.0.1 or http://[::1] (with a port). Got a different address.');
  return u.origin;
}
/** True for any address that names the production project, in any case, in the host or the path. */
export const isProductionUrl = (url) => String(url || '').toLowerCase().includes(PRODUCTION_REF);
/** Chrome flag: the production host does not resolve inside the browser at all (a second wall behind the request filter). */
