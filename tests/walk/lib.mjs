/* ── Logins ────────────────────────────────────────────────────────────────────
 * The seeded people and the rule for their first passwords are in the header and tables of scripts/staging/seed_staging.py.
 * The people are read from that file at run time; the passwords follow the rule (staff: last name lower case + 1234,
 * cadet: last 6 digits of the cadet ID) and are computed in memory. Nothing is stored. An environment variable
 * WALK_PASSWORD_<NAME> (upper case, e.g. WALK_PASSWORD_DIRECTOR) overrides the rule for one login. */
const DOMAIN = 'prep-staging.example';
export function loadSeed() {
  const src = readFileSync(join(REPO, 'scripts', 'staging', 'seed_staging.py'), 'utf8');
  const staff = {};
  for (const m of src.matchAll(/\(\s*"(\w+)",\s*"([A-Za-z]+ [A-Za-z]+)",\s*(True|False)\s*\)/g)) staff[m[1]] = { name: m[2], admin: m[3] === 'True' };
  const cadets = {};
  for (const m of src.matchAll(/\(\s*(30000001\d\d|3009999999),\s*"([A-Za-z]+ Testcadet)",\s*"(\w+)"\s*\)/g)) cadets[m[1]] = { name: m[2], section: m[3] };
  // Twenty more, generated by the seed from a list of first names and four sections (ids 3000000301 up).
  const names = (src.match(/_EXTRA_NAMES = \[([^\]]*)\]/s) || [,''])[1].match(/"([A-Za-z]+)"/g) || [];
  const secs = ((src.match(/_EXTRA_SECTIONS = \[([^\]]*)\]/) || [,''])[1].match(/"(\w+)"/g) || []).map(x => x.replace(/"/g, ''));
  names.forEach((n, i) => { cadets[String(3000000301 + i)] = { name: `${n.replace(/"/g, '')} Testcadet`, section: secs[i % secs.length] }; });
  if (!staff.director || !staff.instructor || !Object.keys(cadets).length) throw new Error('Could not read the seeded people from seed_staging.py.');
  return { staff, cadets };
}
export function staffLogin(seed, key) {
  const s = seed.staff[key]; if (!s) throw new Error(`No seeded staff login "${key}".`);
  const pw = process.env[`WALK_PASSWORD_${key.toUpperCase()}`] || s.name.split(' ').pop().toLowerCase() + '1234';
  return { email: `${key}@${DOMAIN}`, password: pw, label: key };
}
/** `n` is the three digits after "cadet" in the seeded address (101, 102, 999 ...). */
export function cadetLogin(seed, n) {
  const id = n === 999 ? '3009999999' : `3000000${n}`;
  if (!seed.cadets[id]) throw new Error(`No seeded cadet ${n}.`);
  const pw = process.env[`WALK_PASSWORD_CADET${n}`] || id.slice(-6);
  return { email: `cadet${n}@${DOMAIN}`, password: pw, label: `cadet${n}`, id };
}

/* ── The database helper (staging data role) ─────────────────────────────────── */
const PY = process.env.PREP_PYTHON || 'python';
const DBPY = join(HERE, 'db.py');
export const lit = (v) => v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
export function sql(q) {
  try { return JSON.parse(execFileSync(PY, [DBPY, 'sql', q], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 50e6 })); }
  catch (e) { throw new Error('database read failed: ' + String(e.stderr || e.message).split('\n').filter(Boolean).slice(-2).join(' ').slice(0, 300)); }
}
/** statements: [[sql, params|null], ...] in one transaction. */
export function exec(statements) {
  const dir = mkdtempSync(join(tmpdir(), 'walk-'));
  const f = join(dir, 'stmts.json');
  writeFileSync(f, JSON.stringify(statements));
  try { return JSON.parse(execFileSync(PY, [DBPY, 'exec', f], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 50e6 })); }
  catch (e) { throw new Error('database write failed: ' + String(e.stderr || e.message).split('\n').filter(Boolean).slice(-2).join(' ').slice(0, 300)); }
}

/* ── Checks ──────────────────────────────────────────────────────────────────── */
export const results = [];       // { id, name, status: 'pass'|'fail'|'blocked', detail }
export const faults = [];        // { id, login, steps, expected, actual, where }
const failedIds = new Set();
export function record(id, name, status, detail = '') {
  results.push({ id, name, status, detail });
  if (status !== 'pass') failedIds.add(id);
  console.log(`  [${status === 'pass' ? 'pass' : status === 'fail' ? 'FAIL' : 'BLOCKED'}] ${id} ${name}${detail && status !== 'pass' ? '  -- ' + detail : ''}`);
}
/** Run one named check. It passes when `fn` returns without throwing and without returning false. `needs` lists check ids that must have passed. */
export async function check(id, name, fn, { needs = [] } = {}) {
  const missing = needs.filter(n => failedIds.has(n) || !results.some(r => r.id === n));
  if (missing.length) { record(id, name, 'blocked', `needs ${missing.join(', ')}, which did not pass`); return false; }
  try {
    const r = await fn();
    if (r === false) { record(id, name, 'fail', 'returned false'); return false; }
    record(id, name, 'pass'); return true;
  } catch (e) { record(id, name, 'fail', String(e && e.message || e).slice(0, 500)); return false; }
}
export const blockedBy = (id, name, why) => record(id, name, 'blocked', why);
export function fault(f) { faults.push(f); }
export function assert(cond, msg) { if (!cond) throw new Error(msg); }
export function eq(a, b, what) { if (JSON.stringify(a) !== JSON.stringify(b)) throw new Error(`${what}: expected ${JSON.stringify(b)}, got ${JSON.stringify(a)}`); }
export const wait = (ms) => new Promise(r => setTimeout(r, ms));

