export const productionAttempts = [];     // every request the filter stopped; the walk fails if any appear
export class Session {
  constructor(browser, base, who) { this.browser = browser; this.base = base; this.who = who; this.problems = []; this.confirms = []; this.alerts = []; this.confirmAnswers = []; this.opened = []; }
  static async start(browser, base, login) {
    const s = new Session(browser, base, login);
    s.ctx = await browser.createBrowserContext();
    const page = s.page = await s.ctx.newPage();
    await page.setRequestInterception(true);
    page.on('request', req => {
      const u = req.url();
      if (isProductionUrl(u)) { productionAttempts.push(`${login?.label || "none"}: ${u.slice(0, 60)}`); req.abort('blockedbyclient'); return; }
      req.continue().catch(() => {});
    });
    page.on('pageerror', e => s.problems.push('uncaught: ' + String(e.message).slice(0, 200)));
    page.on('console', m => { if (m.type() === 'error') s.problems.push('console: ' + m.text().slice(0, 200)); });
    page.on('dialog', d => {
      if (d.type() === 'confirm') { s.confirms.push(d.message()); const yes = s.confirmAnswers.length ? s.confirmAnswers.shift() : true; (yes ? d.accept() : d.dismiss()).catch(() => {}); }
      else if (d.type() === 'prompt') { s.alerts.push('prompt: ' + d.message()); d.accept(s.promptAnswer || 'ZZ walk').catch(() => {}); }
      else { s.alerts.push(d.message()); d.accept().catch(() => {}); }
    });
    // A tutor card opens claude.ai in a new window. The walk never leaves for it: window.open is recorded and refused.
    await page.evaluateOnNewDocument(() => { window.__opened = []; window.open = (u) => { window.__opened.push(String(u)); return null; }; });
    if (login) await s.signIn(login);
    return s;
  }
  async signIn(login) {
    const p = this.page;
    await p.goto(`${this.base}/site/login.html`, { waitUntil: 'networkidle2' });
    await p.type('#identifier', login.email);
    await p.type('#password', login.password);
    await Promise.all([p.click('#submit'), p.waitForNavigation({ waitUntil: 'networkidle2', timeout: 30000 }).catch(() => {})]);
    await wait(500);
    if (/login\.html/.test(p.url())) throw new Error(`sign-in failed for ${login.label}: ` + (await this.text('#error')).slice(0, 120));
  }
  async go(path) { await this.page.goto(`${this.base}/site/${path}`, { waitUntil: 'networkidle2' }); await wait(300); return this; }
  async text(sel = 'body') { return this.page.$eval(sel, e => e.innerText).catch(() => ''); }
  async exists(sel) { return !!(await this.page.$(sel)); }
  async visible(sel) { return this.page.$eval(sel, e => !!(e.offsetWidth || e.offsetHeight || e.getClientRects().length)).catch(() => false); }
  async click(sel) { await this.page.waitForSelector(sel, { visible: true, timeout: 15000 }); await this.page.click(sel); }
  /** Click through the page itself: for a control that is off screen or in a closed menu. */
  async jsClick(sel) { await this.page.waitForSelector(sel, { timeout: 15000 }); await this.page.$eval(sel, e => e.click()); }
  async set(sel, value) {
    await this.page.waitForSelector(sel, { timeout: 15000 });
    await this.page.$eval(sel, (e, v) => { e.focus(); e.value = ''; e.dispatchEvent(new Event('input', { bubbles: true })); e.value = v; e.dispatchEvent(new Event('input', { bubbles: true })); e.dispatchEvent(new Event('change', { bubbles: true })); }, value);
  }
  async select(sel, value) { await this.page.waitForSelector(sel, { timeout: 15000 }); await this.page.select(sel, value); }
  async tick(sel, on = true) { await this.page.$eval(sel, (e, v) => { if (e.checked !== v) e.click(); }, on); }
  /** Wait until the page text matches (a RegExp or string). Returns the text. */
  async until(re, { sel = 'body', timeout = 20000 } = {}) {
    const t0 = Date.now(); let t = '';
    while (Date.now() - t0 < timeout) { t = await this.text(sel); if (re instanceof RegExp ? re.test(t) : t.includes(re)) return t; await wait(250); }
    throw new Error(`timed out waiting for ${re} in ${sel}; page says: ${t.replace(/\s+/g, ' ').slice(0, 200)}`);
  }
  async untilSel(sel, { timeout = 20000, visible = false } = {}) {
    try { await this.page.waitForSelector(sel, { timeout, visible }); }
    catch (e) {   // say what the page showed, so a missing element is not a bare timeout
      const t = (await this.text('body')).replace(/\s+/g, ' ').slice(0, 300);
      throw new Error(`${String(e.message).split(/\r?\n/)[0]}; page at ${this.page.url().replace(this.base, '')} says: ${t}; ${this.problems.slice(-2).join(' | ')}`);
    }
  }
  async untilGone(sel, timeout = 20000) { await this.page.waitForFunction(s => !document.querySelector(s), { timeout }, sel); }
  /** Run code in the page, with the site's own client in scope as `db`. */
  async inPage(fn, ...args) {
    // A string given to the debugger protocol runs under the page's rules without needing eval, so the site's content policy is not bent.
    return this.page.evaluate(`(async () => { const { db } = await import('/site/js/supabase.js'); return await (${fn.toString()})(db, ${JSON.stringify(args)}); })()`);
  }
  /** A real file drop: a File, a DataTransfer carrying it, and the dragenter / dragover / drop events a person's drag makes. */
  async dropFile(sel, name, content, type = 'text/csv') {
    await this.page.waitForSelector(sel, { timeout: 15000 });
    await this.page.$eval(sel, (el, n, c, t) => {
      const dt = new DataTransfer(); dt.items.add(new File([c], n, { type: t }));
      for (const ev of ['dragenter', 'dragover', 'drop']) el.dispatchEvent(new DragEvent(ev, { bubbles: true, cancelable: true, dataTransfer: dt }));
    }, name, content, type);
  }
  async opened_() { return this.page.evaluate(() => window.__opened || []); }
  async close() { await this.ctx.close().catch(() => {}); }
}

export function fmtDate(d) { const p = (n) => String(n).padStart(2, '0'); return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`; }
export const inDays = (n) => { const d = new Date(); d.setDate(d.getDate() + n); return d; };

/** One assignment offering with its paths, found by exact title. null when there is none. */
export function itemByTitle(title) {
  const r = sql(`select ao.id, ao.course_offering_id, ao.is_published, ao.due_at, ao.points_possible, ao.switch_policy, ao.grading_mode, a.id as assignment_id, a.title, a.kind_id,
    (select json_agg(json_build_object('delivery',oa.delivery,'grading',oa.grading,'role',oa.grading_role,'pos',oa.position,'modality',act.modality,'slug',act.slug,'activity_id',act.id,'url',act.content->>'artifact_url',
        'nq', jsonb_array_length(coalesce(act.content->'questions','[]'::jsonb)),'qtexts',(select coalesce(json_agg(q->>'text'),'[]'::json) from jsonb_array_elements(coalesce(act.content->'questions','[]'::jsonb)) q)) order by oa.position)
       from offering_activities oa join activities act on act.id=oa.activity_id where oa.assignment_offering_id=ao.id) as paths
    from assignment_offerings ao join assignments a on a.id=ao.assignment_id where a.title=${lit(title)} order by ao.created_at desc limit 1`);
  return r[0] || null;
}
